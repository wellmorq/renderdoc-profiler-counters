function makeZip(entries) {
  const locals = []; const cds = []; let off = 0;
  for (const [name, data] of entries) {
    const comp = zlib.deflateRawSync(data);
    const n = Buffer.from(name);
    const lh = Buffer.alloc(30); lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(8, 8);
    lh.writeUInt32LE(comp.length, 18); lh.writeUInt32LE(data.length, 22); lh.writeUInt16LE(n.length, 26);
    const cd = Buffer.alloc(46); cd.writeUInt32LE(0x02014b50, 0); cd.writeUInt16LE(20, 6); cd.writeUInt16LE(8, 10);
    cd.writeUInt32LE(comp.length, 20); cd.writeUInt32LE(data.length, 24); cd.writeUInt16LE(n.length, 28); cd.writeUInt32LE(off, 42);
    locals.push(lh, n, comp); cds.push(cd, n);
    off += 30 + n.length + comp.length;
  }
  const cdBuf = Buffer.concat(cds);
  const end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cdBuf.length, 12); end.writeUInt32LE(off, 16);
  return Buffer.concat([...locals, cdBuf, end]);
}

test('setup-nvperf extracts the host library from an SDK zip', () => {
  const home = tmp();
  const zip = path.join(home, 'NVIDIA_Nsight_Perf_SDK_2025.5_Windows.zip');
  const dllName = process.platform === 'win32' ? 'nvperf_grfx_host.dll' : 'libnvperf_grfx_host.so';
  fs.writeFileSync(zip, makeZip([
    [`NvPerf/bin/x64/${dllName}`, Buffer.from('REAL')],
    [`NvPerf/samples/D3D12/bin/x64/Release/${dllName}`, Buffer.from('SAMPLE')],
    ['NvPerf/include/nvperf_host.h', Buffer.from('//')],
  ]));
  const prev = { HOME: process.env.HOME, APPDATA: process.env.APPDATA };
  process.env.HOME = home; process.env.APPDATA = path.join(home, 'AppData');
  try {
    const r = setupNvPerf({ from: zip });
    assert.ok(r.ok, r.text);
    const dest = process.platform === 'win32' ? path.join(home, 'AppData', 'renderdoc', 'plugins', 'nv', dllName) : path.join(home, '.renderdoc', 'plugins', 'nv', dllName);
    assert.equal(fs.readFileSync(dest, 'utf8'), 'REAL');
    const miss = setupNvPerf({ from: path.join(home, 'nope.zip') });
    assert.equal(miss.ok, false);
    assert.match(miss.text, /ASK THE USER/);
  } finally {
    process.env.HOME = prev.HOME; process.env.APPDATA = prev.APPDATA;
  }
});

test('rdjob.py is Python 3.6 compatible and expands includes like qrenderdoc', { skip: spawnSync('python3', ['--version']).status !== 0 }, () => {
  const job = path.join(SKILL, 'scripts', 'rdjob.py');
  const code = `
import importlib.util, os
os.environ["RDGPU_IMPORT_ONLY"] = "1"
spec = importlib.util.spec_from_file_location("rdjob", ${JSON.stringify(job)})
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
files = {"main.hlsl": '#include "lib/common.hlsl"\\nfloat4 main() : SV_Target { return F(); }', "lib/common.hlsl": "#pragma once\\nfloat4 F() { return 1; }"}
out = m.expand_includes(files["main.hlsl"], files)
assert "float4 F()" in out and "#include" not in out and "// #pragma once" in out, out
assert m.safe_rel("C:\\\\Users\\\\x\\\\Temp\\\\..\\\\a.hlsl") == "Users/x/Temp/a.hlsl"
print("ok")`;
  const r = spawnSync('python3', ['-c', code], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
  const v = spawnSync('vermin', ['-q', '--no-tips', '--violations', '-t=3.6-', job], { encoding: 'utf8' });
  if (v.status !== null && !v.error) assert.equal(v.stdout.trim(), '', `vermin: ${v.stdout}`);
});

