function writeCase(dir, { actions, counters, state = [], shaders = [], info = {}, files = {} }) {
  fs.mkdirSync(path.join(dir, 'shaders'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'case.json'), JSON.stringify({ version: 1, capture: path.join(dir, 'x.rdc'), host: 'test', options: {} }));
  fs.writeFileSync(path.join(dir, 'info.json'), JSON.stringify({ api: 'D3D11', vendor: 'nVidia', counters: [
    { id: 1, name: 'GPU Duration', unit: 'Seconds', family: 'generic' },
    { id: 12, name: 'PS Invocations', unit: 'Absolute', family: 'generic' },
    { id: 2, name: 'Input Vertices Read', unit: 'Absolute', family: 'generic' },
    { id: 3000001, name: 'l1tex__t_sector_hit_rate.avg.pct', unit: 'Percentage', family: 'nvidia', description: 'hit <br/>rate' },
  ], textures: [], ...info }));
  fs.writeFileSync(path.join(dir, 'actions.jsonl'), actions.map((a) => JSON.stringify(a)).join('\n') + '\n');
  fs.writeFileSync(path.join(dir, 'state.jsonl'), state.map((a) => JSON.stringify(a)).join('\n') + '\n');
  fs.writeFileSync(path.join(dir, 'shaders.json'), JSON.stringify(shaders));
  fs.writeFileSync(path.join(dir, 'counters-generic.json'), JSON.stringify(counters));
  for (const [f, text] of Object.entries(files)) fs.writeFileSync(path.join(dir, 'shaders', f), text);
}

