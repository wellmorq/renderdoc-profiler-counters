const LIVE = process.env.RDGPU_TEST_CAPTURE;
test('live: open + draw + experiment on a real capture', { skip: !LIVE, timeout: 900000 }, () => {
  const work = tmp();
  const cap = path.join(work, path.basename(LIVE));
  fs.copyFileSync(LIVE, cap);
  let r = cli(['open', cap], { timeout: 600000 });
  assert.equal(r.code, 0, r.err);
  assert.match(r.out, /PASSES/);
  const eid = Number((r.out.match(/TOP EVENTS\n.*\n\s*(\d+)\s/) || [])[1]);
  assert.ok(eid > 0);
  r = cli(['draw', cap, String(eid)], { timeout: 300000 });
  assert.equal(r.code, 0, r.err);
  r = cli(['source', cap, String(eid)], { timeout: 300000 });
  assert.equal(r.code, 0, r.err);
  r = cli(['experiment', cap, String(eid), '--repeat', '2'], { timeout: 600000 });
  assert.equal(r.code, 0, r.err);
  assert.match(r.out, /original/);
  r = cli(['session', cap, '--idle', '60'], { timeout: 300000 });
  assert.equal(r.code, 0, r.err);
  assert.match(r.out, /session (ready|open|already open)/);
  r = cli(['draw', cap, String(eid)], { timeout: 300000 });
  assert.equal(r.code, 0, r.err);
  assert.match(r.err, /in the open session|in rdc session/);
  r = cli(['session', cap, '--stop']);
  assert.match(r.out, /session (stop|.*closed)/);
});
